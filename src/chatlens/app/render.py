"""Turns an AnalysisBundle into display-ready values (markdown strings, DataFrames, Plotly figures).
Pure functions, no Gradio import, so the dashboard content is unit-testable."""
from __future__ import annotations

import html

import pandas as pd

from ..analyze import AnalysisBundle, message_level_tests
from ..viz import chart_specs, make_wordcloud, render_plotly


def _md_escape(s) -> str:
    return html.escape(str(s)).replace("|", "\\|").replace("*", "\\*").replace("_", "\\_").replace("`", "\\`")


def status_markdown(b: AnalysisBundle, model_desc: str, synthetic: bool = False) -> str:
    pr, ov = b.parse_report, b.overview
    lines = []
    if synthetic:
        lines.append("> ⚠️ **This is FABRICATED demo data** generated by the synthetic-chat generator. Patterns shown "
                     "reflect generator settings, not human behaviour.\n")
    lines += [f"### Parsed {ov['total_messages']:,} messages from {ov['total_participants']} participants "
              f"({b.meta['chat_type']} chat)",
              f"- **Date range**: {ov['date_start']:%Y-%m-%d} → {ov['date_end']:%Y-%m-%d} ({ov['span_days']} days)"
              if ov["span_days"] else "- Date range unavailable",
              f"- **Format**: {pr['source_format']}, dates read as **{pr['date_order']}**"
              + ("" if pr["date_order_confident"] else " (⚠️ ambiguous — please verify)"),
              f"- **Accounted for**: {pr['header_lines']:,} message headers → {pr['messages']:,} rows "
              f"({pr['system_messages']} system, {pr['media_messages']} media, {pr['deleted_messages']} deleted, "
              f"{pr['multiline_messages']} multi-line merged)",
              f"- **Flagged, not removed**: {pr['invalid_timestamps']} invalid timestamps, "
              f"{pr['duplicate_rows_flagged']} duplicate rows, {pr['empty_messages']} empty",
              f"- **Privacy**: names {'anonymised' if b.meta['anonymized'] else 'shown'}; no data leaves this machine",
              f"- **NLP models**: {_md_escape(model_desc)}"]
    for w in pr["warnings"]:
        lines.append(f"- ⚠️ {_md_escape(w)}")
    return "\n".join(lines)


def quality_table(b: AnalysisBundle) -> pd.DataFrame:
    return pd.DataFrame([{"check": c["name"], "passed": "✅" if c["passed"] else "⚠️", "severity": c["severity"],
                          "detail": c["detail"]} for c in b.quality["checks"]])


def behaviour_markdown(b: AnalysisBundle) -> str:
    rs = b.behavior["response_summary"]
    out = [f"**{rs.get('counted_responses', 0):,} replies counted** (window {rs['window_minutes']} min; "
           f"{rs.get('excluded_beyond_window', 0):,} later turn-changes excluded)."]
    if "overall" in rs:
        o = rs["overall"]
        out.append(f"Median response time **{o['median_min']:.1f} min** (95% CI {o['median_ci95'][0]:.1f}–"
                   f"{o['median_ci95'][1]:.1f}); 90th percentile {o['p90_min']:.0f} min.")
    ex = b.behavior["exchange"]
    if ex:
        out.append(f"{ex['sessions']:,} conversation sessions; {ex['avg_turns_per_session']:.1f} turns per session on "
                   f"average; {ex['back_and_forth_sessions']:,} back-and-forth sessions (≥4 turns).")
    out.append("\n*How to read this*: a “reply” is the first message of a new speaker after someone else spoke. "
               "Exports contain no reply links or read receipts, so this is an **inference**. In groups the reply "
               "may be to someone else. “No observed reply” does **not** mean a message was ignored.")
    return "\n\n".join(out)


def sentiment_markdown(b: AnalysisBundle) -> str:
    s = b.nlp.get("sentiment")
    if not s:
        return "Sentiment analysis was not run."
    lines = [f"Scored **{s['n_scored']:,} of {s['n_text_messages']:,}** text messages (**{s['coverage']:.0%}**).",
             "Coverage by detected language: " + ", ".join(f"{k} {v:.0%}" for k, v in
                                                          sorted(s["coverage_by_language"].items())),
             f"*{s.get('caveat', '')}*"]
    for a in s.get("monitoring", {}).get("alerts", []):
        lines.append(f"⚠️ {_md_escape(a)}")
    t = s.get("participant_difference_test")
    if t:
        lines.append(f"Participants differ in sentiment mix: {t['test']}, p = {t['p_value']:.3g}, "
                     f"{t['effect_name']} = {t['effect_size']:.3f} (**{t['magnitude']}** effect).")
    return "\n\n".join(lines)


def topics_markdown(b: AnalysisBundle) -> str:
    t = b.nlp.get("topics")
    if not t:
        return "Topic analysis was not run."
    if "topics" not in t:
        return f"Topics skipped: {_md_escape(t.get('skipped'))}"
    out = [f"**{t['k']} topics** found with NMF over {t['n_sessions_used']} conversation sessions "
           f"(NPMI coherence {t['npmi_coherence']:.2f}, diversity {t['topic_diversity']:.2f}). "
           f"k was chosen from {len(t['sweep'])} candidates by coherence.", ""]
    for i, (words, n) in enumerate(zip(t["topics"], t["sizes"], strict=True), 1):
        out.append(f"{i}. {_md_escape(', '.join(words[:8]))} — *{n} sessions*")
    out.append(f"\n*{t['caveat']}*")
    return "\n".join(out)


def keywords_table(b: AnalysisBundle) -> pd.DataFrame:
    k = b.nlp.get("keywords", {}).get("keywords")
    if not k:
        return pd.DataFrame(columns=["method", "top keywords"])
    return pd.DataFrame([{"method": m, "top keywords": ", ".join(w for w, _ in v[:12])} for m, v in k.items()])


def stats_table(b: AnalysisBundle) -> pd.DataFrame:
    tests = message_level_tests(b)
    rows = []

    def add(name, t):
        if t:
            rows.append({"comparison": name, "test": t["test"], "p-value": f"{t['p_value']:.3g}",
                         "effect size": f"{t['effect_size']:.3f} ({t['effect_name']})"
                         if t.get("effect_size") is not None else "-", "magnitude": t.get("magnitude") or "-",
                         "p<0.05": "yes" if t["significant"] else "no", "note": t.get("note", "")})
    for k, v in tests["participant_comparison"].items():
        add(k.replace("_", " "), v)
    add("weekend vs weekday volume", (tests["weekend_vs_weekday"] or {}).get("test"))
    add("response time by responder", tests["response_time_difference"])
    add("sentiment by participant", tests["sentiment_participant_difference"])
    return pd.DataFrame(rows, columns=["comparison", "test", "p-value", "effect size", "magnitude", "p<0.05", "note"])


def figures(b: AnalysisBundle) -> dict:
    return {name: render_plotly(spec) for name, spec in chart_specs(b).items()}


def wordcloud_figure(b: AnalysisBundle):
    """Word cloud from Latin/Devanagari words only (Arabic script needs text shaping; see viz.py)."""
    tw = b.text["top_words"]
    freq = {w: int(c) for w, c in zip(tw["word"], tw["count"], strict=True) if not any("\u0600" <= ch <= "\u06ff"
                                                                                       for ch in w)}
    return make_wordcloud(freq)
